A = {1, 3, 5, 7}
B = {1, 4, 5, 8}

print("Union: ", A | B)
print("Intersection: ", A & B)
print("Difference: ", A - B)
print("Symetric Diference: ", A ^ B)

"""
| = Union (Gabungan)

& = Intersection (Irisan)

- = Difference (Selisih)

^ = Symetric Diference (Data yang berbeda)
"""