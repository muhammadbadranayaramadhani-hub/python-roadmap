#Method validasi

kata_random = input("Masukkan sesuatu: ")

print("isalpha() :", kata_random.isalpha())
print("isdigit() :", kata_random.isdigit())
print("isalnum() :", kata_random.isalnum())
print("islower() :", kata_random.islower())
print("isupper() :", kata_random.isupper())